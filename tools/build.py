#!/usr/bin/env python3
"""Assemble the UI for both surfaces from the shared sources in ui/.

    ui/accounts.css   shared design (one stylesheet, theme comes in through --ca-* vars)
    ui/icons.js       provider logos + icons (ICONS, PROVIDERS, PCOLOR)
    ui/panel.src.js   VS Code webview renderer

Outputs
    vscode-extension/media/panel.css   VS Code theme mapping + accounts.css
    vscode-extension/media/panel.js    panel.src.js with icons injected
    hermes/desktop-plugins/claude-accounts/plugin.js   CSS + icons injected between /*@@…*/ markers

Run:  python3 tools/build.py [--install]   (--install also copies the Hermes pane into ~/.hermes)
"""
import os
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UI = ROOT / "ui"

VSCODE_THEME = """/* generated by tools/build.py — edit ui/accounts.css */
:root{
  --ca-good:var(--vscode-charts-green,#3fb950);--ca-warn:var(--vscode-charts-yellow,#d29922);--ca-bad:var(--vscode-charts-red,#f85149);
  --ca-accent:var(--vscode-focusBorder,#4c8dff);--ca-t1:var(--vscode-foreground);--ca-t2:var(--vscode-descriptionForeground);
  --ca-t3:color-mix(in srgb,var(--vscode-descriptionForeground) 82%,transparent);--ca-t4:color-mix(in srgb,var(--vscode-descriptionForeground) 58%,transparent);
  --ca-line:var(--vscode-panel-border,rgba(127,127,127,.3));--ca-line2:color-mix(in srgb,var(--vscode-panel-border,rgba(127,127,127,.3)) 70%,transparent);
  --ca-bg:var(--vscode-sideBar-background,var(--vscode-editor-background,#1e1e1e));
  --ca-menu-bg:var(--vscode-menu-background,var(--vscode-editorWidget-background,#252526));
  --ca-input-bg:var(--vscode-input-background,transparent);
  --ca-btn-bg:var(--vscode-button-background);--ca-btn-fg:var(--vscode-button-foreground);
  --ca-mono:var(--vscode-editor-font-family,ui-monospace,monospace)
}
html,body{margin:0;padding:0;height:100%}
body{font-family:var(--vscode-font-family);font-size:12px;color:var(--ca-t1);background:transparent;overflow:hidden}
"""

HERMES_THEME = """.ca{--ca-good:var(--ui-green,#3fb950);--ca-warn:var(--ui-yellow,#d29922);--ca-bad:var(--ui-red,#f85149);
  --ca-accent:var(--ui-accent,#4c8dff);--ca-line:var(--ui-stroke-secondary,rgba(127,127,127,.25));
  --ca-line2:var(--ui-stroke-tertiary,rgba(127,127,127,.15));--ca-t1:var(--ui-text-primary,inherit);
  --ca-t2:var(--ui-text-secondary,inherit);--ca-t3:var(--ui-text-tertiary,inherit);--ca-t4:var(--ui-text-quaternary,var(--ca-t3));
  --ca-bg:var(--ui-bg-editor,var(--ui-bg-sidebar,#16161a));--ca-menu-bg:var(--ui-bg-popover,var(--ui-bg-editor,#1c1c21));
  --ca-mono:var(--font-mono,ui-monospace,monospace)}
"""


def inject(text: str, start: str, end: str, payload: str) -> str:
    pat = re.compile(re.escape(start) + r".*?" + re.escape(end), re.S)
    if not pat.search(text):
        raise SystemExit(f"marker {start} not found")
    return pat.sub(lambda _m: f"{start}\n{payload}\n{end}", text, count=1)


def main() -> None:
    css = (UI / "accounts.css").read_text()
    icons = (UI / "icons.js").read_text().strip()
    if "`" in css or "${" in css:
        raise SystemExit("accounts.css must not contain backticks or ${ (it is embedded in a JS template)")

    media = ROOT / "vscode-extension" / "media"
    (media / "panel.css").write_text(VSCODE_THEME + css)
    js = (UI / "panel.src.js").read_text()
    (media / "panel.js").write_text(inject(js, "/*@@ICONS*/", "/*@@END_ICONS*/", icons))

    hp = ROOT / "hermes" / "desktop-plugins" / "claude-accounts" / "plugin.js"
    src = hp.read_text()
    src = inject(src, "/*@@ICONS*/", "/*@@END_ICONS*/", icons)
    src = inject(src, "/*@@CSS*/", "/*@@END_CSS*/", "const CSS_SHARED = `\n" + HERMES_THEME + css + "`")
    hp.write_text(src)
    # one engine, three homes: VS Code bundles it, Hermes loads providers.py from engine/
    core = ROOT / "core"
    (ROOT / "vscode-extension" / "core").mkdir(exist_ok=True)
    (ROOT / "hermes" / "plugins" / "claude-accounts" / "engine").mkdir(parents=True, exist_ok=True)
    for f in ("claude_accounts.py", "providers.py", "routing.py"):
        shutil.copy(core / f, ROOT / "vscode-extension" / "core" / f)
    for f in ("providers.py", "routing.py"):
        shutil.copy(core / f, ROOT / "hermes" / "plugins" / "claude-accounts" / "engine" / f)
    for d in ("claude-code",):
        dst = ROOT / "vscode-extension" / d
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(ROOT / d, dst)
    print("built:", media / "panel.css", media / "panel.js", hp, "engine → vscode-extension/core, hermes/…/engine", sep="\n  ")

    if "--install" in sys.argv:
        dst = Path(os.environ.get("HERMES_HOME", Path.home() / ".hermes")) / "desktop-plugins" / "claude-accounts" / "plugin.js"
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(hp, dst)
        print("installed:", dst)


if __name__ == "__main__":
    main()
